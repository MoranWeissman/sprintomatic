#!/usr/bin/env python3
"""Build walkthrough.html from walkthrough-template.html + the drawings.

Run it from the folder that holds the template (a feature's design/ or demo/):

    python3 <this-skill>/kit/build-walkthrough.py

It does three things:

  1. pastes the kit's house-style.css into the {{HOUSE_STYLE}} slot
  2. pastes each drawing into the file as data, so walkthrough.html opens
     offline and keeps working wherever you send it
  3. refuses to write a broken file

Drawings are named, never numbered:

    <img src="{{diagram:run-the-tests.svg}}">

The old way was {{FLOW8}} — the 9th item in a list. Add a flow in the middle
and every slide after it silently showed the wrong picture. Names can't do
that.
"""
import base64
import pathlib
import re
import sys

KIT = pathlib.Path(__file__).resolve().parent
HERE = pathlib.Path.cwd()
TEMPLATE = HERE / "walkthrough-template.html"
OUT = HERE / "walkthrough.html"
DIAGRAMS = HERE / "diagrams"

GENERATED_HEADER = (
    "<!-- GENERATED by build-walkthrough.py from walkthrough-template.html.\n"
    "     Do NOT edit this file — your change is lost on the next build.\n"
    "     Edit walkthrough-template.html instead. -->\n"
)


def die(msg):
    sys.exit("build-walkthrough: " + msg)


if not TEMPLATE.exists():
    die("no walkthrough-template.html in %s — run me from the folder that has it" % HERE)

html = TEMPLATE.read_text(encoding="utf-8")

# ---- 1. the house stylesheet ---------------------------------------------
css_path = KIT / "house-style.css"
if "{{HOUSE_STYLE}}" in html:
    if not css_path.exists():
        die("house-style.css is missing from the kit at %s" % KIT)
    html = html.replace("{{HOUSE_STYLE}}", css_path.read_text(encoding="utf-8"))

# ---- 2. the drawings ------------------------------------------------------
# Only OUTSIDE comments. Slides for parts with no yes yet live inside a
# comment block, and a picture pasted in there is invisible weight.
COMMENT = re.compile(r"<!--.*?-->", re.S)
parts = COMMENT.split(html)          # the live html, comments removed
comments = COMMENT.findall(html)     # kept as-is, untouched

wanted = sorted(set(re.findall(r"\{\{diagram:([^}]+)\}\}", "".join(parts))))
if not wanted:
    print("note: no {{diagram:...}} placeholders outside comments")

missing = [n for n in wanted if not (DIAGRAMS / n).exists()]
if missing:
    die("these drawings are named in the template but not in diagrams/: " + ", ".join(missing))

bitmap_labels = []
for name in wanted:
    raw = (DIAGRAMS / name).read_bytes()
    # A draw.io export made without --embed-svg-fonts false turns every label
    # into a picture of text: huge file, blurry when zoomed in front of a room.
    if name.lower().endswith(".svg") and b"data:image/png" in raw:
        bitmap_labels.append(name)
    uri = "data:image/svg+xml;base64," + base64.b64encode(raw).decode()
    parts = [p.replace("{{diagram:%s}}" % name, uri) for p in parts]

# ---- 3. refuse to write a broken file -------------------------------------
for p in parts:
    if "{{" in p:
        at = p.index("{{")
        die("a placeholder was left unfilled: " + p[at:at + 40].replace("\n", " "))

# stitch the live html and the comments back together, in order
html = "".join(
    x for pair in zip(parts, comments + [""]) for x in pair
)

OUT.write_text(GENERATED_HEADER + html, encoding="utf-8")

kb = len(html) // 1024
print("walkthrough.html built — %d drawings, %d KB" % (len(wanted), kb))

if bitmap_labels:
    print("")
    print("!! These drawings have bitmap labels — their text is pictures, not text.")
    print("!! It goes blurry the moment someone zooms it in the room.")
    for n in bitmap_labels:
        print("   - " + n)
    print("!! Re-export each one and build again:")
    print("   drawio -x -f svg -e --theme light --embed-svg-fonts false \\")
    print("          -o diagrams/<name>.svg diagrams/<name>.drawio")

if kb > 1500:
    print("")
    print("!! %d KB is heavy for a file the dashboard shows in a preview frame." % kb)
    print("!! Usually this means a drawing still carries bitmap labels.")
